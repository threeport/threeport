package apiserver

import (
	"fmt"
	"path/filepath"
	"slices"

	. "github.com/dave/jennifer/jen"

	cli "github.com/threeport/threeport/pkg/cli/v0"
	sdk "github.com/threeport/threeport/pkg/sdk/v0"
	"github.com/threeport/threeport/pkg/sdk/v0/gen"
	"github.com/threeport/threeport/pkg/sdk/v0/util"
)

// GenAddCustomRoutes generates the function to add custom routes to the API
// server.
func GenAddCustomRoutes(gen *gen.Generator, sdkConfig *sdk.SdkConfig) error {
	for _, versionConf := range gen.GlobalVersionConfig.Versions {
		f := NewFile("routes")
		f.HeaderComment("generated by 'threeport-sdk gen' but will not be regenerated - intended for modification")

		f.ImportAlias("github.com/labstack/echo/v4", "echo")
		if gen.Module {
			f.ImportAlias("github.com/threeport/threeport/pkg/api-server/v0/routes", "tp_routes")
		}

		if !gen.Module {
			// CustomRoute struct definition
			f.Comment("CustomRoute is a custom route for the API that defines the REST")
			f.Comment("path, HTTP method, and handler function.")
			f.Type().Id("CustomRoute").Struct(
				Id("Path").String(),
				Id("Method").String(),
				Id("Handler").Func().Params(
					Qual("github.com/labstack/echo/v4", "Context"),
				).Error(),
			)
			f.Line()
		}

		// CustomRoutes function
		f.Comment("CustomRoutes returns a list of all custom routes for the API.")
		f.Comment("Any custom routes that are added to the API must be added here.")
		f.Comment("This will ensure the routes are added to the API server and are")
		f.Comment("registered in the ModuleApiRoutes table in the database.")
		if gen.Module {
			f.Func().Id("CustomRoutes").Params(
				Id("h").Op("*").Qual(
					fmt.Sprintf("%s/pkg/api-server/%s/handlers", gen.ModulePath, versionConf.VersionName),
					"Handler",
				),
			).Index().Qual(
				"github.com/threeport/threeport/pkg/api-server/v0/routes",
				"CustomRoute",
			).Block(
				Comment("if the caller doesn't provide a handler, use an empty handler as a dummy"),
				If(Id("h").Op("==").Nil()).Block(
					Id("h").Op("=").Op("&").Qual(
						fmt.Sprintf("%s/pkg/api-server/%s/handlers", gen.ModulePath, versionConf.VersionName),
						"Handler",
					).Values(),
				),
				Line(),
				Comment("Add custom routes here.  Example:"),
				Comment("return []tp_routes.CustomRoute{"),
				Comment("    {Path: api_v0.PathObjectCustom, Method: \"GET\", Handler: h.GetObjectsForCustomPurpose},"),
				Comment("}"),
				Return(Index().Qual(
					"github.com/threeport/threeport/pkg/api-server/v0/routes",
					"CustomRoute",
				).Values()),
			)
		} else {
			f.Func().Id("CustomRoutes").Params(
				Id("h").Op("*").Qual(
					fmt.Sprintf("%s/pkg/api-server/%s/handlers", gen.ModulePath, versionConf.VersionName),
					"Handler",
				),
			).Index().Id("CustomRoute").Block(
				Comment("if the caller doesn't provide a handler, use an empty handler as a dummy"),
				If(Id("h").Op("==").Nil()).Block(
					Id("h").Op("=").Op("&").Qual(
						fmt.Sprintf("%s/pkg/api-server/%s/handlers", gen.ModulePath, versionConf.VersionName),
						"Handler",
					).Values(),
				),
				Line(),
				Comment("Add custom routes here.  Example:"),
				Comment("return []CustomRoute{"),
				Comment("    {Path: api_v0.PathObjectCustom, Method: \"GET\", Handler: h.GetObjectsForCustomPurpose},"),
				Comment("}"),
				Return(Index().Id("CustomRoute").Values()),
			)
		}
		f.Line()

		// AddCustomRoutes function
		f.Comment("AddCustomRoutes adds non-SDK-generated routes to API server for custom use cases.")
		f.Func().Id("AddCustomRoutes").Params(
			Id("e").Op("*").Qual(
				"github.com/labstack/echo/v4",
				"Echo",
			),
			Id("h").Op("*").Qual(
				fmt.Sprintf("%s/pkg/api-server/%s/handlers", gen.ModulePath, versionConf.VersionName),
				"Handler",
			),
		).Block(
			For(
				List(Id("_"), Id("route")).Op(":=").Range().Id("CustomRoutes").Call(Id("h")),
			).Block(
				Id("e").Dot("Add").Call(
					Id("route").Dot("Method"),
					Id("route").Dot("Path"),
					Id("route").Dot("Handler"),
				),
			),
		)

		// write code to file if not excluded by SDK config
		genFilepath := filepath.Join(
			"pkg",
			"api-server",
			versionConf.VersionName,
			"routes",
			"routes.go",
		)
		if slices.Contains(sdkConfig.ExcludeFiles, genFilepath) {
			cli.Info(fmt.Sprintf("source code generation skipped for %s", genFilepath))
		} else {
			fileWritten, err := util.WriteCodeToFile(f, genFilepath, false)
			if err != nil {
				return fmt.Errorf("failed to write generated code to file %s: %w", genFilepath, err)
			}
			if fileWritten {
				cli.Info(fmt.Sprintf("source code to add custom routes written to %s", genFilepath))
			} else {
				cli.Info(fmt.Sprintf("source code to add custom routes already exists at %s - not overwritten", genFilepath))
			}
		}
	}

	return nil
}
