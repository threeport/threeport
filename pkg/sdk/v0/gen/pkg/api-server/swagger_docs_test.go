// TestAModuleRegistersTheRouteToItsDocs covers how a client reaches a
// module's swagger docs: through the core API, which proxies a path to a
// module only when the module registered it. The path is the one the module
// API server serves its docs under, from the same constant, so the two cannot
// drift apart.
func TestAModuleRegistersTheRouteToItsDocs(t *testing.T) {
	generated := generateModuleRegistration(t)

	assert.Contains(t, generated, `const SwaggerPath = "/swagger/" + moduleName`)
	assert.Contains(t, generated, `docsRoute := tp_api.ModuleApiRoute{
		ModuleApiID: existingModApi.ID,
		Path:        tp_util.Ptr(SwaggerPath),
	}`)
	assert.Contains(t, generated, `tp_client.CreateModuleApiRoute(
		tpApiClient,
		tpApiAddr,
		&docsRoute,
	)`)
	assert.Contains(t, generated, `!errors.Is(docsRouteErr, tp_client_lib.ErrConflict)`, "a route registered by an earlier start is already there")

	// registered once the module API it belongs to is known
	resolved := strings.Index(generated, "existingModApi, createFresh, err := resolveModuleApi(")
	registered := strings.Index(generated, "docsRoute := ")
	require.NotEqual(t, -1, resolved)
	assert.Less(t, resolved, registered)
}

// TestAModuleCompilesBeforeItsDocsAreGenerated covers the placeholder docs
// package a module API server imports until the module runs
// GenerateSwaggerDocs.
func TestAModuleCompilesBeforeItsDocsAreGenerated(t *testing.T) {
	t.Chdir(t.TempDir())
	sdkConfig := moduleFixtureSdkConfig()
	sdkConfig.ApiDocs = sdk.ApiDocs{Title: "Widget API", Description: `Manages "widgets"`}

	require.NoError(t, GenModuleSwaggerDocsPlaceholder(moduleFixtureGenerator(), sdkConfig))
	placeholder, err := os.ReadFile(moduleSwaggerDocsPath)
	require.NoError(t, err)

	_, err = parser.ParseFile(token.NewFileSet(), moduleSwaggerDocsPath, placeholder, 0)
	require.NoError(t, err, "the placeholder has to compile, since the module API server imports it")
	assert.Contains(t, string(placeholder), "package docs")
	assert.Contains(t, string(placeholder), `swag.Register(SwaggerInfo.InstanceName(), SwaggerInfo)`, "echo-swagger serves the registered docs")
	assert.Contains(t, string(placeholder), `Title:            "Widget API"`, "the sdk-config title is used")
	assert.Contains(t, string(placeholder), `\"Manages \\\"widgets\\\"\"`, "the description is escaped into the document")

	// the module's generated docs replace it and are never overwritten
	generatedDocs := []byte("package docs\n\n// generated by swag\n")
	require.NoError(t, os.WriteFile(moduleSwaggerDocsPath, generatedDocs, 0600))
	require.NoError(t, GenModuleSwaggerDocsPlaceholder(moduleFixtureGenerator(), sdkConfig))
	kept, err := os.ReadFile(moduleSwaggerDocsPath)
	require.NoError(t, err)
	assert.Equal(t, generatedDocs, kept, "the docs the module generated are kept")
}

// TestAModuleCanExcludeItsPlaceholderDocs covers a module that keeps its own
// docs package by excluding the file.
func TestAModuleCanExcludeItsPlaceholderDocs(t *testing.T) {
	t.Chdir(t.TempDir())
	sdkConfig := moduleFixtureSdkConfig()
	sdkConfig.ExcludeFiles = []string{filepath.Join("pkg", "api-server", "v0", "docs", "docs.go")}

	require.NoError(t, GenModuleSwaggerDocsPlaceholder(moduleFixtureGenerator(), sdkConfig))
	_, err := os.Stat(moduleSwaggerDocsPath)
	assert.True(t, os.IsNotExist(err))
}
