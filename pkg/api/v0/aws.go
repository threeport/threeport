package v0

import (
	"gorm.io/datatypes"
)

// AwsProvider represents an account with the Amazon Web Services (AWS) service provider.
type AwsProvider struct {
	Common `swaggerignore:"true" mapstructure:",squash"`

	// The unique name of an AWS provider.
	Name *string `json:",omitempty" validate:"required" gorm:"not null"`

	// The account ID for the AWS account.
	AccountID *string `json:",omitempty" validate:"required" gorm:"not null"`

	// If true is the AWS provider used if none specified in a definition.
	DefaultProvider *bool `json:",omitempty" validate:"optional" gorm:"default:false"`

	// The region to use for AWS managed services if not specified.
	DefaultRegion *string `json:",omitempty" validate:"required" gorm:"not null"`

	// See pkg/api/v0/aws_validate.go for validation logic
	// of the AccessKeyID and SecretAccessKey fields.

	// The access key ID credentials for the AWS account.
	AccessKeyID *string `json:",omitempty" validate:"optional" encrypt:"true"`

	// The secret key credentials for the AWS account.
	SecretAccessKey *string `json:",omitempty" validate:"optional" encrypt:"true"`

	// The RoleArn to assume for the AWS account.
	RoleArn *string `json:",omitempty" validate:"optional"`

	// The ExternalId to use when assuming a RoleArn for the AWS account. This is
	// automatically generated by the API server if RoleArn is set.
	ExternalId *string `json:",omitempty" validate:"optional"`

	// The cluster instances deployed with this AWS provider.
	AwsEksKubernetesRuntimeInstances []*AwsEksKubernetesRuntimeInstance `json:",omitempty" validate:"optional,association"`
}

// AwsEksKubernetesRuntimeDefinition provides the configuration for EKS cluster instances.
type AwsEksKubernetesRuntimeDefinition struct {
	Common     `swaggerignore:"true" mapstructure:",squash"`
	Definition `mapstructure:",squash"`

	// TODO: add fields for region limitations
	// RegionsAllowed
	// RegionsForbidden

	// The number of zones the cluster should span for availability.
	ZoneCount *int `json:",omitempty" validate:"required" gorm:"not null"`

	// The AWS instance type for the default initial node group.
	DefaultNodeGroupInstanceType *string `json:",omitempty" validate:"required" gorm:"not null"`

	// The number of nodes in the default initial node group.
	DefaultNodeGroupInitialSize *int `json:",omitempty" validate:"required" gorm:"not null"`

	// The minimum number of nodes the default initial node group should have.
	DefaultNodeGroupMinimumSize *int `json:",omitempty" validate:"required" gorm:"not null"`

	// The maximum number of nodes the default initial node group should have.
	DefaultNodeGroupMaximumSize *int `json:",omitempty" validate:"required" gorm:"not null"`

	// The AWS EKS kubernetes runtime instances derived from this definition.
	AwsEksKubernetesRuntimeInstances []*AwsEksKubernetesRuntimeInstance `json:",omitempty" validate:"optional,association"`

	// The kubernetes runtime definition for an EKS cluster in AWS.
	KubernetesRuntimeDefinitionID *uint `json:",omitempty" validate:"required" gorm:"not null" relationship:"marries"`
}

// AwsEksKubernetesRuntimeInstance is a deployed instance of an EKS cluster.
type AwsEksKubernetesRuntimeInstance struct {
	Common         `swaggerignore:"true" mapstructure:",squash"`
	Instance       `mapstructure:",squash"`
	Reconciliation `mapstructure:",squash"`

	// The AWS provider in which the EKS cluster is provisioned.
	AwsProviderID *uint `json:",omitempty" validate:"required" gorm:"not null" relationship:"requires"`

	// The AWS region in which the cluster is provisioned.
	Region *string `json:",omitempty" validate:"optional"`

	// The definition that configures this instance.
	AwsEksKubernetesRuntimeDefinitionID *uint `json:",omitempty" validate:"required" gorm:"not null" relationship:"requires"`

	// An inventory of all AWS resources for the EKS cluster.
	ResourceInventory *datatypes.JSON `json:",omitempty" validate:"optional"`

	// The kubernetes runtime instance associated with the AWS EKS cluster.
	KubernetesRuntimeInstanceID *uint `json:",omitempty" validate:"required" gorm:"not null" relationship:"marries"`
}
